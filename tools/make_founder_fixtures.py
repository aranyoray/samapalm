"""Golden fixtures pinning the ECGFounder preprocessing, so the Kotlin port on the phone feeds the model the
same numbers the Python runner does.

Writes configs/founder_fixtures/preprocess.json: synthetic single-lead strips with a known heart rate, every
intermediate stage of palmppg.ecg.founder.preprocess (resampled, filtered, z-scored windows), the filter
coefficients the chain uses, and the window-combination rules. Run: python tools/make_founder_fixtures.py
"""
from __future__ import annotations

import base64
import json
import math
from pathlib import Path

import numpy as np
from scipy.signal import butter, firwin, iirnotch

from palmppg.ecg import founder_prep as founder

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "configs" / "founder_fixtures"
FS_IN = 300.0


def f32(a) -> str:
    """float32 little-endian, base64: the Kotlin tests read the same bytes."""
    return base64.b64encode(np.asarray(a, dtype="<f4").tobytes()).decode("ascii")


def synth_strip(seconds: float, bpm: float, fs: float = FS_IN, invert: bool = False, seed: int = 3) -> np.ndarray:
    """Lead-I-like beats at a known rate: P, QRS and T as Gaussians, plus slow wander and a little mains hum."""
    rng = np.random.default_rng(seed)
    n = int(round(seconds * fs))
    t = np.arange(n) / fs
    x = np.zeros(n)
    step = 60.0 / bpm
    tb = 0.4
    while tb < seconds:
        for amp, mu, sd in ((0.12, -0.16, 0.030), (-0.10, -0.020, 0.008), (1.00, 0.0, 0.010),
                            (-0.20, 0.025, 0.010), (0.25, 0.180, 0.050)):
            x += amp * np.exp(-0.5 * ((t - (tb + mu)) / sd) ** 2)
        tb += step
    x += 0.08 * np.sin(2 * math.pi * 0.25 * t)                 # baseline wander
    x += 0.02 * np.sin(2 * math.pi * 50.0 * t)                 # mains, which the notch must remove
    x += rng.normal(0.0, 0.004, n)
    return -x if invert else x


def case(name: str, seconds: float, bpm: float, invert: bool, seed: int) -> dict:
    x = synth_strip(seconds, bpm, invert=invert, seed=seed)
    y, ud = founder.resample_to_model(x, FS_IN)
    flip, neg, beats = founder.polarity_check(y)
    w = founder.preprocess(x, FS_IN)
    # the stages, taken apart so a mismatch in the port can be located
    y_signed = -y if flip else y
    win = founder.WIN
    starts = [int(round(s * founder.FS_MODEL)) for s in w.starts_s]
    raw_windows = np.stack([y_signed[s:s + win] for s in starts]) if starts else np.zeros((0, win))
    filtered = founder.filter_bandpass(raw_windows, founder.FS_MODEL) if len(raw_windows) else raw_windows
    return {
        "name": name,
        "known": {"bpm": bpm, "seconds": seconds, "inverted_input": invert},
        "fs_in": FS_IN,
        "strip_f32_b64": f32(x),
        "resample_up_down": list(ud),
        "resampled_f32_b64": f32(y),
        "polarity": {"flipped": bool(flip), "negative_fraction": None if not np.isfinite(neg) else round(float(neg), 9),
                     "beats": int(beats)},
        "n_windows": int(w.x.shape[0]),
        "window_starts_s": [float(s) for s in w.starts_s],
        "filtered_f32_b64": f32(filtered),
        "model_input_f32_b64": f32(w.x),
        "model_input_shape": list(w.x.shape),
    }


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    b_notch, a_notch = iirnotch(50, 30, founder.FS_MODEL)
    b_band, a_band = butter(N=4, Wn=[0.67, 40], btype="bandpass", fs=founder.FS_MODEL)
    doc = {
        "version": 1,
        "note": "Synthetic signals only (no participant data). Generated by tools/make_founder_fixtures.py; "
                "pins palmppg/ecg/founder.py preprocessing for the Kotlin port in android/ecg-model.",
        "fs_model": founder.FS_MODEL,
        "window_samples": founder.WIN,
        "zscore_eps": founder.ZSCORE_EPS,
        "resample_filter": {
            "description": "scipy.signal.resample_poly(x, 5, 3) design: firwin(2*10*5+1, 1/5, kaiser 5.0) * up",
            "up": 5, "down": 3, "half_len": 50,
            "taps_f32_b64": f32(firwin(101, 1.0 / 5.0, window=("kaiser", 5.0)) * 5),
        },
        "notch": {"b": list(map(float, b_notch)), "a": list(map(float, a_notch))},
        "bandpass": {"b": list(map(float, b_band)), "a": list(map(float, a_band))},
        "median_kernel": int(0.4 * founder.FS_MODEL) + 1,
        "combine": {
            "max_rule_indices": sorted(founder.MAX_RULE_LABELS),
            "rhythm_labels": {str(k): v for k, v in founder.RHYTHM_LABELS.items()},
        },
        "cases": [
            case("clean_72bpm_30s", 30.0, 72.0, False, 3),
            case("inverted_60bpm_30s", 30.0, 60.0, True, 4),
            case("short_8s", 8.0, 75.0, False, 5),
        ],
    }
    path = OUT / "preprocess.json"
    path.write_text(json.dumps(doc, indent=1, sort_keys=False) + "\n", encoding="utf-8")
    print(f"wrote {path} ({path.stat().st_size / 1024:.0f} kB)")
    for c in doc["cases"]:
        print(f"  {c['name']}: {c['n_windows']} window(s), polarity flipped={c['polarity']['flipped']}")


if __name__ == "__main__":
    main()
